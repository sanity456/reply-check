const expression = (tree, name) => {
  let found;
  const visit = (node) => {
    if (ts.isVariableDeclaration(node) && node.name.getText(tree) === name) found = node.initializer.getText(tree);
    ts.forEachChild(node, visit);
  };
  visit(tree); assert.ok(found, name); return found;
};
