/** Offline setup consistency only. No new transaction or completed pending test is claimed. */
import assert from 'node:assert/strict';
import { createEvidenceReader } from '../../read-evidence.mjs';
import {createHash} from 'node:crypto';
const root=new URL('../../../',import.meta.url),read=createEvidenceReader(root);
const sha=b=>createHash('sha256').update(b).digest('hex');
const bytes=await read('evidence/human-wallet/20260913-pending-identity-second-setup.json');
assert.equal(sha(bytes),'db34a05407411ca5ee6af58f70e7eb0dd0802fd00e38c5089c1f0f37a0656a48');
const p=JSON.parse(bytes);
assert.equal(p.status,'AWAITING_HUMAN_APPROVAL_AND_IMMEDIATE_ACCOUNT_SWITCH');
for(const pin of [p.baseline,p.capture_helper])assert.equal(sha(await read(pin.path)),pin.sha256);
for(const [path,hash] of Object.entries(p.source_pins))assert.equal(sha(await read(path)),hash,path);
const before=JSON.parse(await read(p.baseline.path));
assert.equal(before.pending_identity_case,'NOT_EXERCISED_FINALIZED_BEFORE_SWITCH');
assert.equal(p.intended_operation.prohibited_resubmission_hash,before.expected.hash);
assert.equal(p.intended_operation.expected_review_count_before,11);
assert.equal(p.intended_operation.expected_review_count_after,12);
assert.equal(p.intended_operation.request_digest,before.stored_review.request_digest);
assert.equal(p.intended_operation.reference_digest,before.stored_review.reference_digest);
for(const key of ['transaction_hash','request_id','review_id'])assert.equal(p.intended_operation[key],null);
assert.ok(Object.values(p.constraints).every(v=>v===false));
assert.equal(p.observations.length,3);
const first=p.observations[0].snapshot,fixture=p.observations[1].snapshot,last=p.observations[2].snapshot;
assert.ok(!first.includes('region "Transaction recovery"'));
assert.ok(!first.includes('TRANSACTION CHECKED'));
assert.ok(!fixture.includes('region "Recorded assessment"'));
assert.ok(last.includes('dialog "Check this reply"'));
assert.ok(last.includes('definition: 0x7cef5d…8d97d0'));
assert.ok(last.includes('Question: '+p.intended_operation.question));
assert.ok(last.includes('Draft: '+p.intended_operation.draft));
assert.ok(last.includes('button "Continue to wallet" [disabled]'));
assert.ok(!last.includes('checkbox "I checked the content and agree to publish it." [checked]'));
assert.ok(!last.includes('region "Transaction recovery"'));
console.log(JSON.stringify({setup_consistency:'PASS',new_transaction:'NOT_SENT',expected_next_count:12,observations:3,pending_identity_case:'AWAITING_HUMAN'},null,2));
