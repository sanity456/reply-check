/** Offline preflight replay; no wallet request or completed network test. */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createEvidenceReader } from '../../read-evidence.mjs';
import { receiptState, verifyReceiptCall } from '../../../lib/reply/receipt.ts';
const root = new URL('../../../', import.meta.url);
const read = createEvidenceReader(root);
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
const bytes = await read('evidence/human-wallet/20260913-pending-network-preparation.json');
assert.equal(sha(bytes), '5d554d035540e2624575b0a651271e1eb5fcdf398584d32872613a0aab3f098e');
const proof = JSON.parse(bytes), live = proof.fresh_read_only_checkpoint;
assert.equal(proof.status, 'PREPARED_AWAITING_SITE_WALLET_B_NO_REQUEST_STAGED');
assert.equal(live.status, 'PASS_SCOPED_UNCHANGED_CHECKPOINT');
for (const pin of [proof.baseline, live.generator]) assert.equal(sha(await read(pin.path)), pin.sha256);
for (const [path, hash] of Object.entries(proof.source_pins)) assert.equal(sha(await read(path)), hash, path);
const baseline = JSON.parse(await read(proof.baseline.path));
assert.deepEqual(live.expected, baseline.expected);
assert.equal(receiptState(live.receipt, live.expected).state, 'success');
assert.equal(await verifyReceiptCall(live.receipt, live.expected), true);
assert.deepEqual(live.decoded_call, baseline.decoded_call);
assert.deepEqual(live.decoded_return_payload, baseline.stored_review);
assert.deepEqual(live.stored_review, baseline.stored_review);
assert.equal(live.deployment_verification.matched, true);
assert.equal(live.deployment_verification.source_sha256, proof.source_pins['contracts/reply_check.py']);
assert.ok(Date.parse(live.receipt_observation.observed_at_utc) >= Date.parse(live.receipt_observation.requested_at_utc));
assert.ok(Date.parse(live.deployment_verification.verified_at_utc) >= Date.parse(live.receipt_observation.observed_at_utc));
assert.equal(live.observations.length, 10);
assert.deepEqual(live.observations.map((row) => row.key), baseline.observations.map((row) => row.key));
for (const row of live.observations) {
  const previous = baseline.observations.find((item) => item.key === row.key);
  assert.equal(row.method, previous.method);
  assert.deepEqual(row.args, previous.args);
  assert.deepEqual(row.output, previous.output);
  assert.ok(Date.parse(row.requested_at_utc) >= Date.parse(live.deployment_verification.verified_at_utc));
  assert.ok(Date.parse(row.observed_at_utc) >= Date.parse(row.requested_at_utc));
}
assert.equal(live.observations.find((row) => row.key === 'reviews').output.length, 13);
assert.equal(proof.intended_operation.expected_review_count_before, 13);
assert.equal(proof.intended_operation.expected_review_count_after, 14);
assert.ok(proof.intended_operation.prohibited_resubmission_hashes.includes(live.expected.hash));
for (const field of ['request_id', 'review_id', 'transaction_hash']) assert.equal(proof.intended_operation[field], null);
assert.equal(proof.initial_browser.visible.account, 'A');
assert.equal(proof.initial_browser.visible.recovery_present, false);
assert.equal(proof.initial_browser.visible.consent_dialog_open, false);
assert.ok(proof.initial_browser.snapshot.includes('button "0x29b8b7…509360"'));
assert.ok(!proof.initial_browser.snapshot.includes('region "Transaction recovery"'));
assert.ok(Object.values(proof.constraints).every((value) => value === false));
assert.equal(proof.checks.length, 5);
console.log(JSON.stringify({ preparation: 'PASS', full_public_outputs: 10, unchanged_reviews: 13, pending_network_test: 'NOT_EXERCISED', request_staged: false, note: 'Offline consistency only. Historical workflow mode does not change application pins or claim public CI.' }, null, 2));
